CREATE TABLE curso (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(100)  NOT NULL UNIQUE,
    titulo           VARCHAR(200)  NOT NULL,
    descripcion      VARCHAR(4000) NOT NULL,
    horas            INTEGER       NOT NULL,
    precio_centimos  INTEGER       NOT NULL,
    nota_minima      INTEGER       NOT NULL,
    num_preguntas    INTEGER       NOT NULL,
    activo           BOOLEAN       NOT NULL
);

CREATE TABLE tema (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id   BIGINT         NOT NULL REFERENCES curso (id),
    orden      INTEGER        NOT NULL,
    titulo     VARCHAR(200)   NOT NULL,
    contenido  VARCHAR(20000) NOT NULL,
    CONSTRAINT uk_tema_curso_orden UNIQUE (curso_id, orden)
);

CREATE TABLE pregunta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id   BIGINT        NOT NULL REFERENCES curso (id),
    enunciado  VARCHAR(1000) NOT NULL,
    correcta   INTEGER       NOT NULL
);

CREATE TABLE pregunta_opcion (
    pregunta_id  BIGINT       NOT NULL REFERENCES pregunta (id),
    posicion     INTEGER      NOT NULL,
    texto        VARCHAR(500) NOT NULL,
    PRIMARY KEY (pregunta_id, posicion)
);

CREATE TABLE intento_examen (
    id            UUID    NOT NULL PRIMARY KEY,
    curso_id      BIGINT  NOT NULL REFERENCES curso (id),
    nota          INTEGER,
    aprobado      BOOLEAN NOT NULL,
    iniciado_en   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    entregado_en  TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE intento_pregunta (
    intento_id   UUID    NOT NULL REFERENCES intento_examen (id),
    posicion     INTEGER NOT NULL,
    pregunta_id  BIGINT  NOT NULL REFERENCES pregunta (id),
    PRIMARY KEY (intento_id, posicion)
);

CREATE TABLE intento_respuesta (
    intento_id   UUID    NOT NULL REFERENCES intento_examen (id),
    pregunta_id  BIGINT  NOT NULL,
    opcion       INTEGER NOT NULL,
    PRIMARY KEY (intento_id, pregunta_id)
);

CREATE TABLE pedido (
    id                UUID         NOT NULL PRIMARY KEY,
    intento_id        UUID         NOT NULL REFERENCES intento_examen (id),
    nombre            VARCHAR(100) NOT NULL,
    apellidos         VARCHAR(150) NOT NULL,
    dni               VARCHAR(9)   NOT NULL,
    email             VARCHAR(254) NOT NULL,
    importe_centimos  INTEGER      NOT NULL,
    estado            VARCHAR(20)  NOT NULL,
    referencia_pago   VARCHAR(255),
    creado_en         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    pagado_en         TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX ix_pedido_referencia_pago ON pedido (referencia_pago);
CREATE INDEX ix_pedido_intento ON pedido (intento_id);

CREATE TABLE diploma (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       UUID        NOT NULL UNIQUE REFERENCES pedido (id),
    codigo          VARCHAR(20) NOT NULL UNIQUE,
    emitido_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    token_descarga  VARCHAR(64) NOT NULL
);
